#!/bin/sh
# The documentation site's generator and checks. POSIX sh, awk and jq.
#
#   sh tools/docs.sh generate          rewrite the generated pages under website/docs
#   sh tools/docs.sh check             write nothing; fail on a generated page that is missing,
#                                      stale or edited, and on a page that breaks the page rules
#   sh tools/docs.sh provenance <site> <commit>
#                                      bind a built site to its commit: .well-known/b10x-site.json,
#                                      .well-known/b10x-routes.json and .nojekyll
#
# The repository root is the parent of this script's directory, or $DOCS_ROOT.
# Exit 0 when everything passes, 1 otherwise, 2 on a usage error.
set -u

root=${DOCS_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}
cd "$root" || exit 1

base=/uxui/
repository=uxui
blob=https://github.com/beyond10x/uxui/blob/main
tree=https://github.com/beyond10x/uxui/tree/main

# Generated page -> its source, one per line. website/docs/<page>.
generated='reference/skill.md
reference/metrics.md
reference/glossary.md
reference/specification.md
roadmap.md
status.md'

marker='generated by tools/docs.sh, do not edit'

# Front matter of a generated page: title, sidebar position, description.
front() {
	printf -- '---\n# %s\ntitle: "%s"\nsidebar_position: %s\ndescription: "%s"\ncustom_edit_url: null\n---\n\n<!-- %s -->\n\n' \
		"$marker" "$1" "$2" "$3" "$marker"
}

# Markdown from stdin made safe for the documentation site: outside fenced blocks and inline code,
# `{` becomes `\{` and `<` before a letter, `/` or `!` becomes `&lt;`.
prose() {
	awk '
	/^[ \t]*(```|~~~)/ { fence = !fence; print; next }
	fence { print; next }
	{
		out = ""; code = 0; n = length($0)
		for (i = 1; i <= n; i++) {
			c = substr($0, i, 1)
			if (c == "`") { code = !code; out = out c; continue }
			if (!code && c == "{") { out = out "\\{"; continue }
			if (!code && c == "<" && substr($0, i + 1, 1) ~ /[A-Za-z\/!]/) { out = out "&lt;"; continue }
			out = out c
		}
		print out
	}'
}

# Body of a Markdown file without its front matter and its first H1.
body() {
	awk '
	NR == 1 && $0 == "---" { fm = 1; next }
	fm { if ($0 == "---") fm = 0; next }
	!h1 && /^# / { h1 = 1; skip = 1; next }
	skip && /^$/ { skip = 0; next }
	!started && /^$/ { next }
	{ skip = 0; started = 1; print }' "$1"
}

page_skill() {
	front "The ui-iteration-loop skill" 1 "The complete text of the skill the plugin ships, generated from its SKILL.md."
	printf '# The ui-iteration-loop skill\n\n'
	printf 'This page is the skill itself: [`plugin/skills/ui-iteration-loop/SKILL.md`](%s/plugin/skills/ui-iteration-loop/SKILL.md), plugin version `%s`. ' \
		"$blob" "$(jq -r .version plugin/.claude-plugin/plugin.json)"
	printf 'Its references are [`heuristics.md`](%s/plugin/skills/ui-iteration-loop/references/heuristics.md), ' "$blob"
	printf '[`review-agents.md`](%s/plugin/skills/ui-iteration-loop/references/review-agents.md) and ' "$blob"
	printf '[`not-available.md`](%s/plugin/skills/ui-iteration-loop/references/not-available.md). ' "$blob"
	printf 'How to install it is on [Getting started](../getting-started.md); one round, step by step, is the [guide](../guides/run-a-round.md).\n\n'
	printf ':::note[Description the hosts read]\n\n%s\n\n:::\n\n' \
		"$(awk 'NR > 1 && /^---$/ { exit } /^description: / { sub(/^description: /, ""); print }' plugin/skills/ui-iteration-loop/SKILL.md)"
	body plugin/skills/ui-iteration-loop/SKILL.md | prose
}

page_metrics() {
	front "Metric catalogue" 2 "The 47 UX metrics of the search engine with their formulas, units, directions and roles, generated from docs/metrics.md."
	printf '# Metric catalogue\n\n'
	printf 'Generated from [`docs/metrics.md`](%s/docs/metrics.md). It is a design: no code computes these metrics yet ([Status](../status.md)). The words are defined in the [Glossary](./glossary.md).\n\n' "$blob"
	body docs/metrics.md | prose
}

page_glossary() {
	front "Glossary" 3 "The words the search engine's specification and documents use, generated from docs/brief.md."
	printf '# Glossary\n\n'
	printf 'Generated from the glossary of [`docs/brief.md`](%s/docs/brief.md). The specification and every page of this site use these words.\n\n' "$blob"
	awk '/^## Glossary/ { on = 1; next } on && /^## / { exit } on' docs/brief.md | awk 'NF || started { started = 1; print }' | prose
}

# One line per declaration of a domain file: kind, name, text (an entity's summary, a command's
# display name), tab-separated.
declarations() {
	awk '
	/^[a-z_]+:/ {
		if (item != "") print kind "\t" item "\t" text
		sec = $1; sub(/:.*/, "", sec); item = ""; next
	}
	(sec == "entities" || sec == "commands" || sec == "views" || sec == "events") && /^  - name: / {
		if (item != "") print kind "\t" item "\t" text
		kind = sec; item = $0; sub(/^  - name: /, "", item); text = ""; next
	}
	item != "" && kind == "entities" && /^      summary: / { text = $0; sub(/^      summary: /, "", text) }
	item != "" && kind == "commands" && /^      display: / { text = $0; sub(/^      display: /, "", text) }
	END { if (item != "") print kind "\t" item "\t" text }' "$1"
}

summary() {
	awk '
	/^summary: >-?$/ { on = 1; next }
	on && /^  / { sub(/^  +/, ""); s = s (s == "" ? "" : " ") $0; next }
	on { exit }
	END { print s }' "$1"
}

page_specification() {
	domains=$(awk '/^domains:/ { on = 1; next } on && /^  - / { sub(/^  - /, ""); print; next } on && /^[^ ]/ { exit }' ess/system.yaml)
	all=$(for d in $domains; do declarations "ess/domains/${d#uxsearch.}.yaml"; done)
	count() { printf '%s\n' "$all" | awk -F '\t' -v k="$1" '$1 == k' | wc -l | tr -d ' '; }
	front "ESS specification" 4 "The ESS specification uxsearch of the UX search engine, domain by domain, generated from ess/."
	printf '# ESS specification `uxsearch`\n\n'
	printf 'Generated from [`ess/`](%s/ess): `system.yaml` and one file per domain under `ess/domains/`. ' "$tree"
	printf 'The engine is specified as an [Executable System Specification](https://beyond10x.github.io/ess/) (format `%s`, specification version `%s`) before any of it is built. ' \
		"$(awk '/^format: / { print $2; exit }' ess/system.yaml)" "$(awk '/^version: / { print $2; exit }' ess/system.yaml)"
	printf 'Its pure functions (mutation operators, the layout model, metric computation, search strategies) are specified by their contracts only.\n\n'
	printf '%s\n\n' "$(summary ess/system.yaml)" | prose
	printf '| domains | entities | commands | views | events |\n|---|---|---|---|---|\n'
	printf '| %s | %s | %s | %s | %s |\n\n' "$(printf '%s\n' $domains | wc -l | tr -d ' ')" \
		"$(count entities)" "$(count commands)" "$(count views)" "$(count events)"
	printf 'The repository gate for the specification:\n\n```console\n'
	printf 'ess specify validate --path ess\ness compile --path ess\n'
	printf 'ess ui check --path ess/ui/studio.ui.yaml --model ess\n'
	printf 'ess ui test --path ess/ui/studio.ui.yaml --model ess ess/ui/tests/studio.yaml\n```\n\n'
	printf 'What ESS cannot express yet, and what the specification does instead, is listed in [`ess/GAPS.md`](%s/ess/GAPS.md). ' "$blob"
	printf 'The studio, the live view of a search, is itself an `ess-ui/1` document: [`ess/ui/studio.ui.yaml`](%s/ess/ui/studio.ui.yaml), with the pages ' "$blob"
	awk '/^pages:/ { on = 1; next } on && /^[a-z_]+:/ { exit } on && /^  [a-z][a-z._]*:$/ { sub(/^  /, ""); sub(/:$/, ""); printf "%s`%s`", (n++ ? ", " : ""), $0 }' ess/ui/studio.ui.yaml
	printf '.\n'
	for d in $domains; do
		file=ess/domains/${d#uxsearch.}.yaml
		decl=$(declarations "$file")
		printf '\n## `%s`\n\n' "$d"
		printf '%s\n\n' "$(summary "$file")" | prose
		printf 'Source: [`%s`](%s/%s).\n\n' "$file" "$blob" "$file"
		if printf '%s\n' "$decl" | grep -q '^entities'; then
			printf '| entity | what it is |\n|---|---|\n'
			printf '%s\n' "$decl" | awk -F '\t' '$1 == "entities" { gsub(/\|/, "\\|", $3); n = $2; sub(/.*\./, "", n); printf "| `%s` | %s |\n", n, $3 }' | prose
			printf '\n'
		fi
		if printf '%s\n' "$decl" | grep -q '^commands'; then
			printf 'Commands: '
			printf '%s\n' "$decl" | awk -F '\t' '$1 == "commands" { n = $2; sub(/.*\./, "", n); printf "%s`%s`", (c++ ? ", " : ""), n }'
			printf '.\n\n'
		fi
		if printf '%s\n' "$decl" | grep -q '^views'; then
			printf 'Views: '
			printf '%s\n' "$decl" | awk -F '\t' '$1 == "views" { n = $2; sub(/.*\./, "", n); printf "%s`%s`", (c++ ? ", " : ""), n }'
			printf '.\n'
		fi
	done
}

page_roadmap() {
	front "Roadmap" 91 "Where uxui stands and the next steps in order, generated from docs/roadmap.md."
	printf '# Roadmap\n\n'
	printf 'Generated from [`docs/roadmap.md`](%s/docs/roadmap.md). Paths name files in the [repository](%s).\n\n' "$blob" "$tree"
	body docs/roadmap.md | prose
}

page_status() {
	status=website/data/status.json
	front "Status" 90 "What uxui ships today, what is specified and what is planned, item by item."
	printf '# Status\n\n'
	jq -r '
	  (.items | map(select(.status == "shipped")) | length) as $s
	  | (.items | map(select(.status == "decided")) | length) as $d
	  | (.items | map(select(.status == "planned")) | length) as $p
	  | "\($s) items are shipped, \($d) are decided and \($p) are planned, as of \(.asOf). **Shipped** means on `main` and usable today. **Decided** means designed and written down in the repository (documents and the ESS specification) with no code behind it. **Planned** means a step on the [Roadmap](./roadmap.md) that has not started. What the evidence does not show is on [Limitations](./limitations.md). This page is generated from `website/data/status.json`, the same file the landing page reads."' "$status"
	jq -r '
	  def glyph: if . == "shipped" then "● shipped" elif . == "decided" then "◐ decided" else "○ planned" end;
	  def esc: gsub("\\|"; "\\|");
	  .items as $items
	  | ($items | reduce .[].area as $a ([]; if any(.[]; . == $a) then . else . + [$a] end))
	  | .[] as $area
	  | "\n## \($area)\n\n| Item | Status | What it means |\n|---|---|---|",
	    ($items[] | select(.area == $area)
	      | "| \(if .href then "[\(.label | esc)](.\(.href | sub("^/docs"; "") | sub("#"; ".md#") | if test("\\.md") then . else . + ".md" end))" else (.label | esc) end) | \(.status | glyph) | \(.detail // "" | esc) |")' "$status" | prose
}

render() {
	case $1 in
	reference/skill.md) page_skill ;;
	reference/metrics.md) page_metrics ;;
	reference/glossary.md) page_glossary ;;
	reference/specification.md) page_specification ;;
	roadmap.md) page_roadmap ;;
	status.md) page_status ;;
	esac
}

fails=0
fail() {
	printf 'FAIL %s\n' "$*"
	fails=$((fails + 1))
}

# The page rules, for every page under website/docs.
rules() {
	for f in $(find website/docs -name '*.md*' | LC_ALL=C sort); do
		case $f in *.mdx) fail "$f: pages are plain Markdown (.md), never .mdx" ;; esac
		[ "$(sed -n 1p "$f")" = "---" ] || { fail "$f: no front matter"; continue; }
		fm=$(awk 'NR == 1 { next } /^---$/ { exit } { print }' "$f")
		for key in title sidebar_position description; do
			printf '%s\n' "$fm" | grep -q "^$key: ." || fail "$f: front matter has no $key"
		done
		case $f in website/docs/concepts/* | website/docs/guides/*)
			for key in lede source; do
				printf '%s\n' "$fm" | grep -q "^$key: ." || fail "$f: front matter has no $key"
			done ;;
		esac
		printf '%s\n' "$fm" | grep -E '^[a-z_]+: ' | grep -vE '^[a-z_]+: "' | grep -E ': .*(: | #)|:$' |
			while IFS= read -r line; do printf 'FAIL %s: unquoted front matter value: %s\n' "$f" "$line"; done
		awk -v f="$f" '
		NR == 1 { fm = 1; next }
		fm { if ($0 == "---") fm = 0; next }
		/^[ \t]*(```|~~~)/ { fence = !fence; next }
		fence { next }
		{
			line = $0; gsub(/`[^`]*`/, "", line)
			if (line ~ /(^|[^\\])\{/) print "FAIL " f ":" NR ": `{` outside code"
			if (line ~ /^(import|export) /) print "FAIL " f ":" NR ": import or export line"
			if (line ~ /<\/?[A-Z]/) print "FAIL " f ":" NR ": capitalised tag"
		}' "$f"
		grep -nE '/hom[e]/|\.engineerin[g]/' "$f" | sed "s|^|FAIL $f:|; s|\$|: internal path|"
		grep -niE 'uilab' "$f" | sed "s|^|FAIL $f:|; s|\$|: names uilab, which uxui does not use|"
	done
}

generate() {
	mode=$1
	out=website/docs
	if [ "$mode" = check ]; then
		out=target/docs-check
		rm -rf "$out"
	fi
	for page in $generated; do
		mkdir -p "$out/$(dirname "$page")"
		render "$page" > "$out/$page" || fail "$page: could not be generated"
		if [ "$mode" = check ]; then
			if [ ! -f "website/docs/$page" ]; then
				fail "website/docs/$page: missing; run sh tools/docs.sh generate"
			elif ! cmp -s "$out/$page" "website/docs/$page"; then
				fail "website/docs/$page: stale or edited by hand; run sh tools/docs.sh generate"
			fi
		fi
	done
	result=$(rules)
	[ -z "$result" ] || { printf '%s\n' "$result"; fails=$((fails + $(printf '%s\n' "$result" | wc -l))); }
	for json in website/product.json website/data/status.json; do
		jq -e . "$json" >/dev/null 2>&1 || fail "$json: not valid JSON"
	done
	[ "$(jq -r .format website/product.json)" = b10x-product-landing/1 ] || fail "website/product.json: format is not b10x-product-landing/1"
	[ "$(jq -r .format website/data/status.json)" = b10x-status/1 ] || fail "website/data/status.json: format is not b10x-status/1"
	jq -e '.items | all(.status == "shipped" or .status == "decided" or .status == "planned")' website/data/status.json >/dev/null ||
		fail "website/data/status.json: a status other than shipped, decided or planned"
}

provenance() {
	site=$1
	commit=$2
	case $commit in *[!0-9a-f]* | '') fail "commit must be 40 lowercase hex digits"; return ;; esac
	[ "${#commit}" -eq 40 ] || { fail "commit must be 40 lowercase hex digits"; return; }
	[ "$commit" != 0000000000000000000000000000000000000000 ] || { fail "commit must be nonzero"; return; }
	[ -f "$site/index.html" ] || { fail "$site holds no built site"; return; }
	mkdir -p "$site/.well-known"
	printf '{\n  "baseUrl": "%s",\n  "commit": "%s",\n  "repository": "%s",\n  "schema": "b10x-project-site/v1"\n}' \
		"$base" "$commit" "$repository" > "$site/.well-known/b10x-site.json"
	# Every page with its sorted element IDs. A client redirect and the trailing-slash copy are no
	# route; a page at x.html answers /<base>x/, a directory index at x/index.html answers /<base>x/.
	(cd "$site" && find . -name '*.html' | sed 's|^\./||' | LC_ALL=C sort) | while IFS= read -r rel; do
		[ "$rel" = 404.html ] && continue
		grep -qE 'http-equiv="?refresh|<!-- b10x-trailing-slash-copy -->' "$site/$rel" && continue
		case $rel in
		index.html) route=$base ;;
		*/index.html) route=$base${rel%index.html} ;;
		*) route=$base${rel%.html}/ ;;
		esac
		printf 'R\t%s\n' "$route"
		grep -oE " id=(\"[^\"]*\"|'[^']*'|[^ >\"']+)" "$site/$rel" | sed -E "s/^ id=[\"']?//; s/[\"']\$//" |
			LC_ALL=C sort -u | sed "s|^|A\t$route\t|"
	done > "$site/.well-known/routes.tsv"
	grep -q "^R	$base\$" "$site/.well-known/routes.tsv" || { rm -f "$site/.well-known/routes.tsv"; fail "the built site has no landing page"; return; }
	jq -R -s --arg repository "$repository" --arg commit "$commit" --arg base "$base" '
	  split("\n") | map(select(length > 0) | split("\t")) as $rows
	  | {schema: "b10x-project-routes/v1", repository: $repository, commit: $commit, baseUrl: $base,
	     routes: ([$rows[] | select(.[0] == "R") | .[1] as $r
	       | {path: $r, anchors: [$rows[] | select(.[0] == "A" and .[1] == $r) | .[2]]}] | sort_by(.path | explode))}' \
		"$site/.well-known/routes.tsv" > "$site/.well-known/b10x-routes.json"
	rm -f "$site/.well-known/routes.tsv"
	: > "$site/.nojekyll"
}

case ${1:-} in
generate) generate write ;;
check) generate check ;;
provenance)
	[ $# -eq 3 ] || { echo "usage: sh tools/docs.sh provenance <site> <commit>" >&2; exit 2; }
	provenance "$2" "$3" ;;
*)
	echo "usage: sh tools/docs.sh generate | check | provenance <site> <commit>" >&2
	exit 2 ;;
esac

[ "$fails" -eq 0 ] || { printf '%s problem(s)\n' "$fails"; exit 1; }
