//! The toy climb (`story:toy-climb`): theme x section order on the ticket page of ESS's partner
//! portal, evaluated on layout model v0 and printed as a ranked frontier.

use std::path::Path;
use std::sync::OnceLock;

use ux_search::climb::{self, Climb, Options};

/// The first line of the golden file until the coordinator generates it.
const PLACEHOLDER: &str = "# to be generated by the coordinator when builds return";

/// The command that writes the golden file, from the repository root.
const GENERATE: &str = "cargo run --manifest-path engine/search/Cargo.toml --locked --quiet -- climb --doc engine/search/tests/fixtures/partner-portal/ui.yaml --page tickets.detail --param id=tk-01 --sizes 120x40,48x40 > engine/search/tests/fixtures/partner-portal.frontier.txt";

fn options(test: &str) -> Options {
    Options {
        target: crate::ticket_page(),
        sizes: vec![(120, 40), (48, 40)],
        state_dir: crate::state_dir(test),
        cap: climb::SECTION_CAP,
    }
}

fn run(test: &str) -> Climb {
    climb::climb(&crate::portal(), &options(test)).unwrap_or_else(|error| panic!("{error}"))
}

/// One climb shared by the tests that only read it.
fn shared() -> &'static Climb {
    static CLIMB: OnceLock<Climb> = OnceLock::new();
    CLIMB.get_or_init(|| run("shared"))
}

fn position(climb: &Climb, id: &str) -> usize {
    climb
        .ranking()
        .iter()
        .position(|&index| climb.variants[index].id == id)
        .unwrap_or_else(|| panic!("no variant {id}; have {:?}", ids(climb)))
}

fn ids(climb: &Climb) -> Vec<&str> {
    climb
        .variants
        .iter()
        .map(|variant| variant.id.as_str())
        .collect()
}

/// (a) The search is deterministic: two climbs in one process print the same bytes.
#[test]
fn two_climbs_in_one_process_print_the_same_bytes() {
    let first = shared().render();
    let second = run("twice-second").render();
    assert!(!first.is_empty());
    assert_eq!(first, second);
}

/// (b) The output is the committed golden file, byte for byte.
#[test]
fn the_climb_prints_the_committed_frontier() {
    let path =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/partner-portal.frontier.txt");
    let golden = std::fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("{}: {error}", path.display()));
    assert!(
        !golden.starts_with(PLACEHOLDER),
        "{} is still the placeholder; generate it from the repository root with:\n{GENERATE}",
        path.display()
    );
    assert_eq!(shared().render(), golden);
}

/// (c) The search discriminates: the variant built to be bad (the default theme, the section
/// that holds the primary action drawn last) ranks below the top variant on its terms, not on
/// its id, and the primary action sits lower in it than in the best variant for that term.
#[test]
fn a_variant_with_the_primary_action_last_ranks_below_the_top() {
    let climb = shared();
    assert_eq!(
        climb.primary.as_deref(),
        Some("pages/tickets.detail/sections/reply/children/send"),
        "the primary action is the first button of tone primary among the page's sections"
    );
    let bad_id = "light:summary,conversation,reply";
    let bad = position(climb, bad_id);
    let ranking = climb.ranking();
    let top = &climb.variants[ranking[0]];
    let worst = &climb.variants[ranking[bad]];
    assert!(bad > 0, "{bad_id} ranks first:\n{}", climb.render());
    assert!(
        top.terms.values() < worst.terms.values(),
        "{bad_id} ties the top variant {} on every term:\n{}",
        top.id,
        climb.render()
    );
    let lowest = climb
        .variants
        .iter()
        .map(|variant| variant.terms.primary_rows)
        .min()
        .unwrap_or(u64::MAX);
    assert!(
        worst.terms.primary_rows > lowest,
        "the primary action of {bad_id} is no lower than in any other variant:\n{}",
        climb.render()
    );
}

/// (d) The search is exhaustive: one variant per theme and section order, each id once.
#[test]
fn the_climb_evaluates_every_theme_for_every_section_order() {
    let climb = shared();
    let themes: Vec<Option<&str>> = climb.themes.iter().map(Option::as_deref).collect();
    assert_eq!(themes, [Some("dark"), Some("dense"), Some("light")]);
    assert_eq!(climb.sections, ["summary", "conversation", "reply"]);
    assert_eq!(climb.orders, 6);
    assert_eq!(climb.variants.len(), climb.themes.len() * climb.orders);
    assert_eq!(climb.variants.len(), 18);
    let mut unique = ids(climb);
    unique.sort_unstable();
    unique.dedup();
    assert_eq!(unique.len(), 18, "{:?}", ids(climb));
    assert_eq!(climb.ranking().len(), 18);
    assert!(
        climb
            .variants
            .iter()
            .all(|variant| variant.refused.is_none()),
        "{}",
        climb.render()
    );
}

/// The frontier is the non-dominated set, printed before the full ranking, one line per variant.
#[test]
fn the_output_prints_the_frontier_then_every_variant_with_its_terms() {
    let climb = shared();
    let text = climb.render();
    let frontier = climb.frontier();
    assert!(!frontier.is_empty());
    let frontier_at = text.find("\nfrontier ").expect("a frontier heading");
    let ranking_at = text.find("\nranking ").expect("a ranking heading");
    assert!(frontier_at < ranking_at);
    let ranking = &text[ranking_at + 1..];
    assert_eq!(ranking.lines().skip(1).count(), 18, "{text}");
    for variant in &climb.variants {
        assert!(
            ranking.contains(&format!(" {} errors=", variant.id)),
            "{} is not in the ranking:\n{text}",
            variant.id
        );
    }
}
